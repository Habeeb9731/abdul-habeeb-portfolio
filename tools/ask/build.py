#!/usr/bin/env python3
"""Build the knowledge the "Ask my portfolio" chat answers from.

Joins tools/ask/profile.md with the case studies in tools/case-studies/data/projects.json
and writes functions/api/_knowledge.js. Run it after changing either file.

Usage:
  python3 tools/ask/build.py          write the file
  python3 tools/ask/build.py --check  exit 1 if it would change
"""
import html, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(ROOT, 'functions', 'api', '_knowledge.js')


def text(v):
    return re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', '', v or ''))).strip()


def project(p):
    lines = [f'### {p["title"]} ({text(p.get("label"))})', text(p.get('summary'))]
    links = [f'{k}: {p[k]}' for k in ('live', 'repo') if p.get(k)]
    if links:
        lines.append('Links: ' + ' · '.join(links))
    for k, v in p.get('meta', []):
        lines.append(f'{text(k)}: {text(v)}')
    if p.get('ov_p'):
        lines.append(text(p['ov_p']))
    for key in ('challenge', 'solution'):
        if p.get(key):
            head, items = p[key]
            lines.append(f'{key.title()}: {text(head)}')
            lines += [f'- {text(i)}' for i in items]
    if p.get('features'):
        lines.append('Features: ' + '; '.join(f'{text(f[1])}: {text(f[2])}' for f in p['features']))
    for k, v in p.get('tech', []):
        lines.append(f'{text(k)}: {text(v)}')
    if p.get('stack'):
        lines.append('Stack: ' + ', '.join(p['stack']))
    if p.get('learned'):
        lines.append('What he learned: ' + text(p['learned']))
    lines.append(f'Case study: https://abdulhabeeb.com/projects/{p["slug"]}/')
    return '\n'.join(l for l in lines if l)


def main():
    profile = open(os.path.join(HERE, 'profile.md'), encoding='utf-8').read().strip()
    projects = json.load(open(os.path.join(ROOT, 'tools', 'case-studies', 'data', 'projects.json'), encoding='utf-8'))
    doc = profile + '\n\n## Projects\n\n' + '\n\n'.join(project(p) for p in projects) + '\n'
    out = ('// Generated by tools/ask/build.py from tools/ask/profile.md and the case studies. Do not edit.\n'
           f'export default {json.dumps(doc, ensure_ascii=False)};\n')
    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    if '--check' in sys.argv:
        print('up to date' if old == out else 'would change')
        sys.exit(0 if old == out else 1)
    if old != out:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        open(OUT, 'w', encoding='utf-8').write(out)
    print(f'knowledge: {len(doc):,} characters (~{len(doc) // 4:,} tokens)')


if __name__ == '__main__':
    main()
